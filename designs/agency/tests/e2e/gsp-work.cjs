// GSP · Admissions, 5 Nov: My work (this role's own copy of GSP · Admin's My Work).
const { chromium } = require('playwright');
const URL = process.env.GSP_URL || require('url').pathToFileURL(require('path').resolve(__dirname, '../../dist-artifact/index.html')).href;
let pass = 0, fail = 0;
const ok = (l, c, x = '') => { c ? pass++ : fail++; console.log(`${c ? 'PASS' : 'FAIL'}  ${l}${x ? '  ' + x : ''}`); };
const wait = (p, ms = 300) => p.waitForTimeout(ms);
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1440, height: 1000 } });
  await ctx.addInitScript(() => { try { if (!sessionStorage.getItem('init')) { localStorage.clear(); localStorage.setItem('gsp-proto-role', 'gsp-team'); localStorage.setItem('gsp-theme', 'light'); sessionStorage.setItem('init', '1'); } } catch {} });
  const p = await ctx.newPage(); const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.goto(URL + '#portal-verified'); await wait(p, 1800);
  const navs = (await p.locator('.pnav__label').allInnerTexts()).map((x) => x.trim());
  ok('menu: My work under Inbox', navs.indexOf('My work') === navs.indexOf('Inbox') + 1, navs.join('|'));
  await p.locator('.pnav__item', { hasText: 'My work' }).click(); await wait(p, 600);
  const main = () => p.locator('main').innerText();
  ok('title in sentence case, a one-line lead', (await p.locator('h1').first().innerText()) === 'My work' && (await main()).includes('Tasks waiting on you and your team'));
  const views = (await p.locator('.gw-views .ichip').allInnerTexts()).map((x) => x.replace(/\s+/g, ' ').trim());
  ok('views: Assigned to me 12, My team 20, Waiting on others 10', views.join('|') === 'Assigned to me 12|My team 20|Waiting on others 10', views.join('|'));
  ok('tiles: 12 assigned, 5 breached', (await p.locator('.gw-tile').first().innerText()).replace(/\s+/g, ' ').startsWith('12 Assigned to me 5 breached'));
  const first = await p.locator('.gw-tab tbody tr').first().innerText();
  ok('the record is the application: GSP number, university and region', first.includes('GSP-24097') && first.includes('University of Wollongong · India') && first.includes('Breached'));
  ok('a paused task says what the RP is asked for', (await main()).includes('Paused while the RP answers: Gap explanation document'));
  ok('a later due date reads as a day', /Due (Mon|Tue|Wed|Thu|Fri) \d+ Nov/.test(await main()));
  ok('Reassign and Mark as completed on each of mine', (await p.getByRole('button', { name: /^Mark as completed/ }).count()) === 12);
  await p.getByRole('button', { name: 'Mark as completed Process the refund for Sujan Karki' }).click(); await wait(p);
  ok('…completed: 11 left', (await p.locator('.gw-tab tbody tr').count()) === 11);
  await p.locator('.gw-views .ichip', { hasText: 'My team' }).click(); await wait(p);
  ok('My team: SLA status and Assigned to filters', (await p.locator('.gw-filter').count()) === 2);
  await p.locator('#gw-assigned').click(); await wait(p); await p.locator('.imp__opt', { hasText: 'Not assigned' }).click(); await p.locator('.imp__acts .btn--secondary').click(); await wait(p);
  ok('…Not assigned: 2 tasks, each with Assign', (await p.locator('.gw-tab tbody tr').count()) === 2 && (await p.getByRole('button', { name: /^Assign / }).count()) === 2);
  await p.locator('#gw-tick-all').click({ force: true }); await wait(p, 200);
  await p.getByRole('button', { name: 'Assign 2' }).click(); await wait(p, 500);
  ok('Assign 2 tasks: People in India Admissions, searchable', (await p.locator('.sheet').last().innerText()).includes('People in India Admissions'));
  await p.locator('#gw-who').fill('Alfiya'); await wait(p); await p.locator('[role=option]', { hasText: 'Alfiya Khan' }).first().click();
  await p.locator('.sheet').last().getByRole('button', { name: 'Assign', exact: true }).click(); await wait(p, 400);
  ok('…assigned: none left unassigned', (await main()).includes('No tasks match these filters.'));
  await p.getByRole('button', { name: 'Clear filters' }).click(); await wait(p);
  await p.locator('.gw-views .ichip', { hasText: 'Waiting' }).click(); await wait(p);
  ok('Waiting on others: 10 records with timers', (await p.locator('.gw-tab tbody tr').count()) === 10 && (await main()).includes('a chase task is raised'));
  ok('no page errors', errs.length === 0, errs.slice(0, 2).join(' | '));
  console.log(`${pass} passed, ${fail} failed`);
  await b.close();
})();
