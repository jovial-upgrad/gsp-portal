// Inbox categories (Nesil, 5 Nov): the Category dropdown, the Not linked nudge (link or forward), in GSP · Admissions.
const { chromium } = require('playwright');
const URL = process.env.GSP_URL || require('url').pathToFileURL(require('path').resolve(__dirname, '../../dist-artifact/index.html')).href;
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
let pass=0; const fails=[]; const ok=(c,m)=>c?pass++:fails.push(m);
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1440, height: 1000 } });
  await ctx.addInitScript(() => { if (!sessionStorage.getItem('init')) { localStorage.setItem('gsp-proto-role', 'gsp-team'); localStorage.setItem('gsp-theme', 'light'); localStorage.setItem('gsp-proto-link', JSON.stringify({ mode: 'off', app: '' })); sessionStorage.setItem('init', '1'); } });
  const p = await ctx.newPage(); const errs=[]; p.on('pageerror', e=>errs.push(e.message));
  await p.goto(URL + '#home'); await wait(1800);
  await p.locator('nav button', { hasText: /^Inbox$/ }).first().click(); await wait(800);
  const pickCat = async (label) => { await p.locator('#mb-cat').click(); await wait(250); await p.locator('[role=listbox] [role=option]', { hasText: label }).first().click(); await wait(400); };
  await p.locator('#mb-cat').click(); await wait(250);
  const opts = await p.locator('[role=listbox] [role=option]').allInnerTexts(); console.log(JSON.stringify(opts));
  ok(opts.length===5, 'five category options');
  await p.keyboard.press('Escape'); await wait(200);
  await pickCat('Not linked');
  const n0 = await p.locator('.mbx__row').count(); ok(n0>0 && (await p.locator('.mbx__row .mbx__tag--todo').count())===n0, 'Not linked lists only unlinked mail');
  await p.locator('.mbx__row').first().click(); await wait(600);
  ok(await p.locator('.mbx__nudge').isVisible(), 'nudge shows on an unlinked mail');
  await p.locator('.mbx__nudge').getByRole('button', { name: 'Link', exact: true }).click(); await wait(300);
  ok((await p.locator('.mbx__nudge .field__msg--error').count())===1, 'Link with nothing chosen says so');
  await p.locator('.mbx__nudge-row').first().locator('button').first().click(); await wait(300);
  await p.locator('[role=listbox] [role=option]').first().click(); await wait(300);
  await p.locator('.mbx__nudge').getByRole('button', { name: 'Link', exact: true }).click(); await wait(600);
  ok((await p.locator('.mbx__nudge').count())===0 && (await p.locator('.mbx__app').count())===1, 'linking shows the application');
  ok((await p.locator('.mbx__row').count())===n0-1, 'it leaves Not linked');
  await p.locator('.mbx__row').first().click(); await wait(500);
  await p.locator('.mbx__nudge-row').nth(1).locator('button').first().click(); await wait(300);
  await p.locator('[role=listbox] [role=option]', { hasText: 'GSP Commission' }).first().click(); await wait(300);
  await p.locator('.mbx__nudge').getByRole('button', { name: 'Forward' }).click(); await wait(600);
  ok((await p.locator('.mbx__note', { hasText: 'Forwarded to GSP Commission' }).count())===1, 'forwarding notes where it went');
  ok((await p.locator('.mbx__row').count())===n0-2, 'it leaves Not linked');
  await pickCat('Forwarded');
  ok((await p.locator('.mbx__row').count())===3, 'Forwarded lists 3');
  await pickCat('Others'); ok((await p.locator('.mbx__row').count())>=1, 'Others lists mail');
  await p.locator('.mbx__row').first().click(); await wait(400); ok((await p.locator('.mbx__nudge').count())===0, 'no nudge on Others');
  await p.setViewportSize({ width: 390, height: 844 }); await wait(400);
  await p.locator('.mbx__back').click(); await wait(400);
  await pickCat('Not linked'); await p.locator('.mbx__row').first().click(); await wait(500);
  ok(errs.length===0, 'no page errors '+errs.join('|'));
  console.log(pass+' passed, '+fails.length+' failed', fails);
  await b.close();
})();
