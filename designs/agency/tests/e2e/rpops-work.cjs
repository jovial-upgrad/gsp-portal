// GSP · RP Ops, 5 Nov: My work (this role's own copy).
const { chromium } = require('playwright');
const URL = process.env.GSP_URL || require('url').pathToFileURL(require('path').resolve(__dirname, '../../dist-artifact/index.html')).href;
let pass = 0, fail = 0;
const ok = (l, c, x = '') => { c ? pass++ : fail++; console.log(`${c ? 'PASS' : 'FAIL'}  ${l}${x ? '  ' + x : ''}`); };
const wait = (p, ms = 300) => p.waitForTimeout(ms);
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1440, height: 1000 } });
  await ctx.addInitScript(() => { try { if (!sessionStorage.getItem('init')) { localStorage.clear(); localStorage.setItem('gsp-proto-role', 'rp-ops'); localStorage.setItem('gsp-theme', 'light'); sessionStorage.setItem('init', '1'); } } catch {} });
  const p = await ctx.newPage(); const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.goto(URL + '#home'); await wait(p, 1800);
  const navs = (await p.locator('.pnav__label').allInnerTexts()).map((x) => x.trim());
  ok('menu: My work under Inbox', navs.indexOf('My work') === navs.indexOf('Inbox') + 1, navs.join('|'));
  await p.locator('.pnav__item', { hasText: 'My work' }).click(); await wait(p, 600);
  const main = () => p.locator('main').innerText();
  const views = (await p.locator('.rw-views .ichip').allInnerTexts()).map((x) => x.replace(/\s+/g, ' ').trim());
  ok('views: Assigned to me 0, My team 16, Waiting on others 0', views.join('|') === 'Assigned to me 0|My team 16|Waiting on others 0', views.join('|'));
  ok('Assigned to me: empty, saying where tasks come from', (await main()).includes('Nothing assigned to you') && (await main()).includes('New tasks appear here when a task rule fires.'));
  await p.locator('.rw-views .ichip', { hasText: 'My team' }).click(); await wait(p);
  ok('My team: 16 tasks, Queues, SLA status and Assigned to filters', (await p.locator('.rw-tab tbody tr').count()) === 16 && (await p.locator('.rw-filter').count()) === 3);
  const first = await p.locator('.rw-tab tbody tr').first().innerText();
  ok('…breached first: Check in with Educareer Services, RP, India, Escalated to Admin', first.includes('Check in with Educareer Services') && first.includes('RP') && first.includes('India') && first.includes('Escalated to Admin') && first.includes('Breached'));
  await p.locator('#rw-queues').click(); await wait(p);
  ok('…the Queues filter offers RP Ops', (await p.locator('.imp__opt').allInnerTexts()).map((x) => x.trim()).join('|') === 'RP Ops');
  await p.locator('.imp__acts .btn--secondary').click(); await wait(p);
  await p.locator('#rw-tick-all').click({ force: true }); await wait(p, 200);
  ok('tick all: 16 ticked, Assign 16', (await p.getByRole('button', { name: 'Assign 16' }).count()) === 1);
  await p.getByRole('button', { name: 'Assign 16' }).click(); await wait(p, 500);
  await p.locator('#rw-who').click(); await wait(p);
  await p.locator('[role=option]', { hasText: 'Rohan Desai' }).first().click();
  await p.locator('.sheet').last().getByRole('button', { name: 'Assign', exact: true }).click(); await wait(p, 400);
  ok('…assigned to me: Assigned to me now 16', (await p.locator('.rw-views .ichip').first().innerText()).replace(/\s+/g, ' ').includes('16'));
  await p.locator('.rw-views .ichip', { hasText: 'Waiting' }).click(); await wait(p);
  ok('Waiting on others: empty, saying what shows there', (await main()).includes('Nothing is waiting on others'));
  ok('no page errors', errs.length === 0, errs.slice(0, 2).join(' | '));
  console.log(`${pass} passed, ${fail} failed`);
  await b.close();
})();
