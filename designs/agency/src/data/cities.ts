export type CityOption = { city: string; state: string };

/**
 * The cities to pick from: the state's, once there is one; before that, the whole country's, each with its state
 * (a city in two of geo.json's levels is listed once, in the larger). Empty where there's no list.
 */
export function citiesFor(country: string, state = ''): CityOption[] {
  const byState = CITIES_BY_STATE[country];
  if (!byState) return [];
  if (state) return (byState[state] ?? []).map((city) => ({ city, state }));
  const seen = new Set<string>();
  const all: CityOption[] = [];
  for (const [st, list] of Object.entries(byState))
    for (const city of list)
      if (!seen.has(city)) {
        seen.add(city);
        all.push({ city, state: st });
      }
  return all.sort((a, b) => a.city.localeCompare(b.city));
}

/** Whether the country has a city list at all. */
export const hasCityList = (country: string) => !!CITIES_BY_STATE[country];
